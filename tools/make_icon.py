"""Draws the port's own icon (an original design, no game art) and writes
res/meguarace.ico (16..256 px) and src/icon_data.h (64x64 RGBA for the
window icon). Run: python3 tools/make_icon.py
"""
import os
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = 1024


def draw():
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    # Rounded tile: night sky fading to violet at the horizon.
    sky = Image.new("RGBA", (S, S))
    sd = ImageDraw.Draw(sky)
    for y in range(S):
        t = y / S
        sd.line([(0, y), (S, y)], fill=(int(18 + 70 * t), int(10 + 12 * t), int(48 + 60 * t), 255))
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).rounded_rectangle([24, 24, S - 24, S - 24], radius=190, fill=255)
    im.paste(sky, (0, 0), mask)
    d = ImageDraw.Draw(im)
    hy = 430                                    # horizon
    # Sun behind the horizon, striped.
    d.pieslice([332, hy - 180, 692, hy + 180], 180, 360, fill=(255, 170, 40, 255))
    for i, y in enumerate(range(hy - 120, hy, 34)):
        d.rectangle([300, y, 724, y + 8 + i * 2], fill=(int(18 + 70 * y / S), int(10 + 12 * y / S), int(48 + 60 * y / S), 255))
    # Ground.
    road = [(0, S), (S, S), (S, hy), (0, hy)]
    gmask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(gmask).polygon(road, fill=255)
    gmask = Image.composite(gmask, Image.new("L", (S, S), 0), mask)
    ground = Image.new("RGBA", (S, S), (14, 8, 30, 255))
    im.paste(ground, (0, 0), gmask)
    d = ImageDraw.Draw(im)
    # Neon road edges and grid converging on the vanishing point.
    vx = S // 2
    for x0, col in ((-260, (0, 230, 255, 255)), (S + 260, (0, 230, 255, 255))):
        d.line([(vx, hy), (x0, S)], fill=col, width=22)
    for k in range(1, 7):
        y = hy + (S - hy) * (k / 7) ** 1.8
        w = 6 + k * 3
        d.line([(30, y), (S - 30, y)], fill=(255, 40, 200, 170), width=w)
    # The car: a low wedge seen from behind, orange body, cyan glass.
    cx, by = S // 2, 860
    body = [(cx - 300, by), (cx + 300, by), (cx + 270, by - 120), (cx + 170, by - 175),
            (cx - 170, by - 175), (cx - 270, by - 120)]
    d.polygon([(x + 14, y + 24) for x, y in body], fill=(0, 0, 0, 150))       # shadow
    d.polygon(body, fill=(235, 70, 30, 255))
    d.polygon([(cx - 270, by - 120), (cx + 270, by - 120), (cx + 300, by), (cx - 300, by)], fill=(190, 40, 20, 255))
    d.polygon([(cx - 140, by - 170), (cx + 140, by - 170), (cx + 190, by - 128), (cx - 190, by - 128)],
              fill=(80, 230, 255, 255))
    # Wing and tail lights.
    d.rectangle([cx - 320, by - 215, cx + 320, by - 190], fill=(40, 20, 60, 255))
    d.rectangle([cx - 300, by - 205, cx - 270, by - 120], fill=(40, 20, 60, 255))
    d.rectangle([cx + 270, by - 205, cx + 300, by - 120], fill=(40, 20, 60, 255))
    d.rectangle([cx - 250, by - 95, cx - 130, by - 60], fill=(255, 240, 120, 255))
    d.rectangle([cx + 130, by - 95, cx + 250, by - 60], fill=(255, 240, 120, 255))
    # Exhaust flames.
    for sx in (cx - 60, cx + 60):
        d.polygon([(sx - 30, by), (sx + 30, by), (sx, by + 90)], fill=(255, 150, 30, 255))
        d.polygon([(sx - 14, by), (sx + 14, by), (sx, by + 50)], fill=(255, 250, 200, 255))
    # Tile border glow.
    edge = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(edge).rounded_rectangle([24, 24, S - 24, S - 24], radius=190, outline=(255, 60, 210, 255), width=18)
    im = Image.alpha_composite(im, edge)
    return im


def main():
    im = draw()
    sizes = [16, 24, 32, 48, 64, 128, 256]
    os.makedirs(os.path.join(ROOT, "res"), exist_ok=True)
    big = im.resize((256, 256), Image.LANCZOS)
    big.save(os.path.join(ROOT, "res", "meguarace.ico"), sizes=[(s, s) for s in sizes])
    big.save(os.path.join(ROOT, "res", "meguarace.png"))
    small = im.resize((64, 64), Image.LANCZOS).convert("RGBA")
    data = small.tobytes()
    lines = ["// Generated by tools/make_icon.py: the port's own icon (no game art),",
             "// 64x64 RGBA, for the window icon.", "#pragma once", "",
             "static const int kIconSize = 64;", "static const unsigned char kIconRGBA[] = {"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 16]) + ",")
    lines.append("};")
    with open(os.path.join(ROOT, "src", "icon_data.h"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
