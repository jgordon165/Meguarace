#!/bin/sh
# Rebuilds quad_shaders.h from quad.vert/.frag and edge.vert/.frag: glslang to
# SPIR-V, then xsdk's xsc (xenos-toolchain) to Xenos containers, with xsdk's
# register split, and each shader's literal constants (the Xenos has no
# immediates: the renderer uploads them before drawing).
#   usage: build_shaders.sh <x360-sdk folder>   (its build/host/libxsc.so made)
set -e
sdk=$1
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
for n in quad.vert quad.frag edge.vert edge.frag; do
    glslang -G --target-env opengl "$here/$n" -o "$tmp/$n.spv" >/dev/null
done
(cd "$sdk/xenos-toolchain" && python3 - "$tmp" "$here/quad_shaders.h" <<'PY'
import struct, sys
from pathlib import Path
from xasm.program import XSDK_REGISTERS
from xsc import spirv
from xsc.lower import lower_ex
tmp, out = sys.argv[1], sys.argv[2]
lines = ["/* Generated by build_shaders.sh from quad.vert/.frag and edge.vert/.frag (xsdk's xsc). */",
         "#ifndef MEGARACE_QUAD_SHADERS_H", "#define MEGARACE_QUAD_SHADERS_H", "", "#include <stdint.h>", ""]
for src, name in (("quad.vert", "quad_vertex"), ("quad.frag", "quad_pixel"),
                  ("edge.vert", "edge_vertex"), ("edge.frag", "edge_pixel")):
    blob, literals = lower_ex(spirv.Module.parse(Path(f"{tmp}/{src}.spv").read_bytes()), XSDK_REGISTERS, True)
    blob += b"\0" * (-len(blob) % 4)
    words = struct.unpack(f">{len(blob)//4}I", blob)
    lines.append(f"static const uint32_t {name}_shader[] = {{")
    for i in range(0, len(words), 6):
        lines.append("    " + ", ".join(f"0x{w:08X}" for w in words[i:i+6]) + ",")
    lines += ["};"]
    for entry in literals:
        if not (isinstance(entry[0], int) and len(entry[1]) == 4):
            sys.exit(f"{src}: a constant the renderer doesn't set: {entry}")
    if literals:
        lines.append(f"/* {src}'s literals: constant register, then its four floats. */")
        lines.append(f"static const float {name}_literals[][5] = {{")
        for reg, v in literals:
            lines.append(f"    {{ {reg}, " + ", ".join(f"{float(x)!r}f" for x in v) + " },")
        lines += ["};"]
    lines.append(f"enum {{ {name.upper()}_LITERALS = {len(literals)} }};")
    lines.append("")
lines.append("#endif")
open(out, "w").write("\n".join(lines) + "\n")
PY
)
rm -rf "$tmp"
