#!/bin/sh
# Rebuilds quad_shaders.h from quad.vert and quad.frag: glslang to SPIR-V,
# then xsdk's xsc (xenos-toolchain) to Xenos containers.
#   usage: build_shaders.sh <x360-sdk folder>   (its build/host/libxsc.so made)
set -e
sdk=$1
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
for s in vert frag; do
    glslang -G --target-env opengl "$here/quad.$s" -o "$tmp/quad.$s.spv"
    (cd "$sdk/xenos-toolchain" && python3 -m xsc.lower "$tmp/quad.$s.spv" -o "$tmp/quad.$s.bin" >/dev/null)
done
python3 - "$tmp" "$here/quad_shaders.h" <<'PY'
import struct, sys
tmp, out = sys.argv[1], sys.argv[2]
lines = ["/* Generated by build_shaders.sh from quad.vert and quad.frag (xsdk's xsc). */",
         "#ifndef MEGARACE_QUAD_SHADERS_H", "#define MEGARACE_QUAD_SHADERS_H", "", "#include <stdint.h>", ""]
for stage, name in (("vert", "quad_vertex_shader"), ("frag", "quad_pixel_shader")):
    data = open(f"{tmp}/quad.{stage}.bin", "rb").read()
    data += b"\0" * (-len(data) % 4)
    words = struct.unpack(f">{len(data)//4}I", data)
    lines.append(f"static const uint32_t {name}[] = {{")
    for i in range(0, len(words), 6):
        lines.append("    " + ", ".join(f"0x{w:08X}" for w in words[i:i+6]) + ",")
    lines += ["};", ""]
lines.append("#endif")
open(out, "w").write("\n".join(lines) + "\n")
PY
rm -rf "$tmp"
